@dataclass
class Entry:
    name: str
    guest_args: list[str]
    # Returns the extra -V/-a flags (identical for both engines) this
    # entry needs, given a fresh scratch directory; None if the entry
    # needs no volume/assign at all.
    setup: Callable[[Path], list[str]] | None
    # Exact expected stdout lines (order matters, no normalization
    # applied) when known ahead of time from test/suite/<name>.py
    # itself; None when comparison instead reads test/data/<name>.txt
    # (see `data_file`).
    expected: list[str] | None = None
    # Basename of a checked-in ground-truth file under test/data/, for
    # a three-way comparison instead of (or in addition to) `expected`.
    data_file: str | None = None
    # An already-filed volamos-side issue this entry's FAIL is tracked
    # by, for entries deliberately left as a visible FAIL rather than
    # moved into KNOWN_DIVERGENCES (a real, unfixed volamos bug --
    # KNOWN_DIVERGENCES is reserved for vamos's own divergences). Purely
    # informational: printed alongside the FAIL, doesn't suppress it.
    tracking_issue: str | None = None
    # Applied to volamos's, vamos's, and `expected`'s own line lists
    # before comparing -- for output whose real AmigaOS ordering isn't
    # guaranteed (e.g. an ExNext directory listing), matching
    # compare_vamos.py's own `dirtest` normalization. `None` (the
    # default) compares lines exactly as produced, in order.
    normalize: Callable[[list[str]], list[str]] | None = None


def setup_dos_match(tmpdir: Path) -> list[str]:
    """A scratch `SYS:` with the exact `c`/`devs`/`libs`/`s`/`t`
    skeleton `test/suite/dos_match.py`'s own expected output assumes --
    supplied explicitly (not relying on either engine's own `SYS:`
    defaults, which no longer agree with each other -- see the module
    doc)."""
    sys_dir = tmpdir / "sys"
    for name in ("c", "devs", "libs", "s", "t"):
        (sys_dir / name).mkdir(parents=True)
    return ["-V", f"SYS:{sys_dir}"]


def setup_dos_examine(tmpdir: Path) -> list[str]:
    """A scratch `TEST:` volume with a `bla` subdirectory containing
    exactly `test/suite/dos_examine.py`'s own fixture: a 14-byte file
    `foo` ("hello, world!\\n") and an empty directory `bar` -- `bla`
    itself (not the volume root) is what gets Locked/Examined, so
    `fib_FileName` reports "bla", matching the real test's own
    expectation."""
    bla = tmpdir / "bla"
    bla.mkdir()
    (bla / "foo").write_text("hello, world!\n")
    (bla / "bar").mkdir()
    return ["-V", f"TEST:{tmpdir}"]


def setup_dos_seek(tmpdir: Path) -> list[str]:
    """A scratch `TEST:` volume -- `dos_seek` creates its own file
    (`Open(..., MODE_NEWFILE)`), so nothing needs to pre-exist inside
    it."""
    test_dir = tmpdir / "test"
    test_dir.mkdir()
    return ["-V", f"TEST:{test_dir}"]


