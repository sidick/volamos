def run_one(
    binary: list[str], extra_flags: list[str], program_path: Path, guest_args: list[str]
) -> tuple[str, int]:
    cmd = [*binary, *extra_flags, str(program_path), *guest_args]
    result = subprocess.run(cmd, capture_output=True, text=True, timeout=30)
    return result.stdout, result.returncode


def load_data_file(checkout: Path, name: str) -> list[str]:
    path = checkout / "test" / "data" / name
    with path.open() as f:
        return [line.rstrip("\n") for line in f]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--amitools-checkout",
        required=True,
        help="path to a local amitools checkout with a built test/bin corpus "
        "(e.g. ~/src/amitools) -- never fetched or copied by this script",
    )
    parser.add_argument(
        "--volamos",
        default=str(REPO_ROOT / "target" / "release" / "volamos"),
        help="path to the volamos binary (default: target/release/volamos)",
    )
    parser.add_argument(
        "--vamos",
        default="vamos",
        help="path to the vamos binary (default: 'vamos' on $PATH)",
    )
    args = parser.parse_args()

    checkout = Path(args.amitools_checkout).expanduser().resolve()
    bin_dir = checkout / "test" / "bin"
    if not bin_dir.is_dir():
        print(f"error: {bin_dir} not found -- is --amitools-checkout correct?", file=sys.stderr)
        return 2

    results = []  # (name, status, detail)
    for entry in CORPUS:
        program = bin_dir / f"{entry.name}_{FLAVOR}"
        if not program.exists():
            results.append((entry.name, "SKIP", f"{program} not found"))
            continue

        with tempfile.TemporaryDirectory(prefix=f"compare-amitools-{entry.name}-") as tmp:
            extra = entry.setup(Path(tmp)) if entry.setup else []
            vol_stdout, vol_code = run_one([args.volamos], extra, program, entry.guest_args)
        with tempfile.TemporaryDirectory(prefix=f"compare-amitools-{entry.name}-") as tmp:
            extra = entry.setup(Path(tmp)) if entry.setup else []
            vam_stdout, vam_code = run_one(
                [args.vamos, "-q"], extra, program, entry.guest_args
            )

        vol_lines = vol_stdout.splitlines()
        vam_lines = vam_stdout.splitlines()

        ground_truth = entry.expected
        if ground_truth is None and entry.data_file is not None:
            ground_truth = load_data_file(checkout, entry.data_file)

        if entry.normalize is not None:
            vol_lines = entry.normalize(vol_lines)
            vam_lines = entry.normalize(vam_lines)
            if ground_truth is not None:
                ground_truth = entry.normalize(ground_truth)

        mismatches = []
        if vol_lines != vam_lines or vol_code != vam_code:
            mismatches.append(
                f"volamos vs vamos differ: volamos={vol_lines!r} exit={vol_code} "
                f"vamos={vam_lines!r} exit={vam_code}"
            )
        if ground_truth is not None:
            if vol_lines != ground_truth:
                mismatches.append(f"volamos vs ground truth: {vol_lines!r} != {ground_truth!r}")
            if vam_lines != ground_truth:
                mismatches.append(f"vamos vs ground truth: {vam_lines!r} != {ground_truth!r}")

        if not mismatches:
            results.append((entry.name, "PASS", ""))
        elif entry.name in KNOWN_DIVERGENCES:
            reason, issue = KNOWN_DIVERGENCES[entry.name]
            results.append((entry.name, "KNOWN", f"{reason} ({issue})"))
        else:
            detail = "; ".join(mismatches)
            if entry.tracking_issue:
                detail += f" [tracked: {entry.tracking_issue}]"
            results.append((entry.name, "FAIL", detail))

    width = max(len(name) for name, _, _ in results)
    for name, status, detail in results:
        line = f"{name:<{width}}  {status}"
        if detail:
            line += f"  -- {detail}"
        print(line)

    failed = [r for r in results if r[1] == "FAIL"]
    if failed:
        # "FAIL" (as opposed to KNOWN_DIVERGENCES) means an unfixed
        # volamos-side bug, not "nobody knows about this yet" -- an
        # entry can (and, right now, mostly does) have both a FAIL
        # status and a [tracked: ...] issue link at the same time; the
        # exit code stays non-zero either way until it's actually fixed.
        print(f"\n{len(failed)} divergence(s) attributed to volamos", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
