#!/usr/bin/env python3
"""Compares volamos against `vamos` using amitools' *own* test corpus
(`test/bin`/`test/suite`/`test/data` in an external amitools checkout,
e.g. `~/src/amitools`), rather than volamos's own hand-written fixtures
(that's `tools/compare_vamos.py`).

## Why a separate corpus from `compare_vamos.py`

amitools ships ~40 small real C programs, each pre-built with up to
four real Amiga compilers (`test/bin/<name>_<flavor>[_dbg]`: gcc, SAS/C
(`sc`), vbcc (`vc`), agcc), a `pytest` suite (`test/suite/*.py`) pinning
down each one's exact invocation and expected output, and checked-in
ground-truth output files (`test/data/*.txt`) for several. Multiple
real compilers' differing startup/calling conventions have found real
bugs in this project before (the `exectest` A6-convention issue --
`docs/plan.md`), so this is a meaningfully different, larger corpus
than volamos's own ~6 fixtures, not just more of the same.

## Licensing: local-only, external checkout, never bundled

amitools is GPLv2; volamos is MIT/Apache-2.0. Nothing under `test/src`,
`test/bin`, or `test/data` is ever copied into this repo -- `--amitools-checkout`
must point at an already-existing local checkout (there is no default;
unlike `--volamos`'s own `target/release/volamos`, there's no sensible
default for an external GPL checkout). Same posture
`tools/compare_three_way.py` already uses for its own external,
never-bundled assets (a proprietary AmiBake corpus and a Kickstart ROM
image) -- see that script's own module doc. This script is local-only
for the same reason: promoting it into CI (`tools/compare_vamos.py`'s
own `compare` job) is a plausible, separate future step once the
initial entries below are proven, not part of this first cut.

## Explicit, identical volume config per entry -- not either engine's
## own defaults

volamos (since issue #43) and `vamos`'s own test suite (via its
`test.vamosrc`) each install a *different* default `sys:` skeleton by
design -- `vamos`'s test suite assigns `sys:` to its own `ram:` auto-
volume, producing `c`/`s`/`libs`/`devs`/`t` subdirectories through
`vamos`'s own auto-assign machinery; volamos's own defaults produce a
persistent `SYS:` with `envarc`/`env` added and `t` living under `RAM:`
instead. Reconciling those two independent "zero-config" mechanisms
isn't the point of this harness -- each `CORPUS` entry instead supplies
the *same* explicit `-V`/`-a` flags to both engines, sidestepping
either side's own defaults entirely.

## Usage

    python3 tools/compare_amitools_suite.py --amitools-checkout ~/src/amitools

Exits non-zero if any corpus entry not fully explained by
`KNOWN_DIVERGENCES` disagrees between volamos and `vamos`, or (for an
entry with a `test/data/*.txt` ground-truth file) if either engine
disagrees with that checked-in expected output -- a stronger check than
two-engine agreement alone, which would miss a bug both sides happen to
share. **Caveat**: amitools' own `test/data/*.txt` files are themselves
generated by capturing a `vamos` run (`test/helper/runner.py`'s
`--gen-data` mode), not independently verified against real hardware --
so for a case where volamos and `vamos` disagree and the `.txt` file
sides with `vamos`, that's still really just "agrees with vamos", one
data point, not two.

## Corpus (14 entries so far; see this module's own "explicitly
## deferred" note in `docs/plan.md`'s matching entry for what's
## intentionally not here yet -- companion-binary-building entries,
## other compiler flavors, and CI promotion)

Multiple runs against this corpus have found and fixed eight real
volamos bugs (issues #45, #46, #47, #48, #51, #53, #55 -- #45,
`RawDoFmt`'s `%b` never converting its `BPTR` argument to a real
address; #46, `AnchorPath`'s `ap_Buf` always stripping the caller's own
device prefix instead of tracking whatever qualification level the
caller's own pattern text had; #47, `Seek()` never rejecting a target
position beyond EOF; #48, `%x`/`%lx` hex digit case; #51,
`IEEEDPCeil()`'s negative-zero sign; #53, `mathffp.library`/
`mathtrans.library`'s FFP sign/exponent bits swapped plus wrong
overflow/underflow saturation; #55, `dos.library/FindArg` not
implemented at all -- confirmed correct against real Kickstart 3.1
hardware via Copperline (A600 model, for Gayle IDE support, and for
#46 specifically, a genuine in-memory FFS synthesized from a host
directory via `[ide]`, not just `--run`'s convenience mount, after an
initial `--run`-based fix attempt caused a direct, reproducible
regression in volamos's own `Delete` -- see issue #46's own comment
thread for the full story), one further, narrower gap surfaced by
fixing #46 (issue #58, `MatchFirst`'s volume-root `fib_FileName`/
`APF_DirChanged` flags), and two divergences confirmed attributed to
`vamos` itself via the same real-hardware verification (#49, `CheckDate`
wday; #52, qNaN sign bit for domain-error results) -- concrete evidence
this corpus finds things volamos's own ~6 fixtures don't. `dos_match`
(#58) and `math_fast_trans` (#53's own residual 1-ULP transcendental
noise) are the only entries still a tracked `FAIL` below.

- `dos_match`: `MatchFirst`/`MatchNext`/`ap_Buf` via a real `AnchorPath`
  scan of a scratch `SYS:` -- exercises `crate::dosanchor`.
- `dos_seek`: `Open(MODE_NEWFILE)`/`Write`/`Seek`/`Read`/`IoErr` round
  trip against a scratch `TEST:` volume -- fully self-contained (the
  program creates its own file).
- `dos_examine`: `Lock`/`Examine`/`ExNext` against a scratch `TEST:`
  subdirectory (order-tolerant, matching `test/suite/dos_examine.py`'s
  own "either ExNext order" acceptance).
- `dos_findarg`: `dos.library/FindArg` -- implemented (#55, fixed).
- `util_date`, `vprintf`, `exec_rawdofmt`, `dos_stdout`, `util_muldiv`,
  `exec_copymem`, `math_double`, `math_double_trans`, `math_fast`,
  `math_fast_trans`: no volume needed at all; the `math_*`/`util_date`/
  `vprintf`/`exec_rawdofmt` entries compare three-way against their
  checked-in `test/data/*.txt`.

Explicitly **not** added despite being self-contained: `test_hello`/
`test_raise` (they call `vamostest.library`, a `vamos`-only internal
testing/debugging library with no real-AmigaOS counterpart -- there is
nothing for volamos to implement here, this isn't a gap) and
`exec_initstruct` (`InitStruct()`'s byte-code interpreter is a real
gap, but volamos's own `execlib.rs` already documents it as deferred
to a later phase -- not a quick add) and `math_single`/
`math_single_trans` (need `mathieeesingbas.library`/
`mathieeesingtrans.library`, which volamos doesn't implement at all;
same "real gap, not a quick add" reasoning).
"""

